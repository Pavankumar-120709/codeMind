from typing import List, Dict, Any, Optional, AsyncIterator
import os
import json
import re
from dotenv import dotenv_values
from app.core.config import settings
from app.utils.logger import logger
from app.llm.prompts import (
    SYSTEM_RAG_PROMPT,
    ARCHITECTURE_ANALYSIS_PROMPT,
    BUG_ANALYSIS_PROMPT,
    TEST_GENERATION_PROMPT
)

class GeminiClient:
    def __init__(self):
        self.api_key = settings.GEMINI_API_KEY
        self.model_name = settings.GEMINI_MODEL
        self._client = None
        self._init_client()

    def _refresh_key_if_changed(self):
        env_path = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), ".env")
        if os.path.exists(env_path):
            vals = dotenv_values(env_path)
            new_key = vals.get("GEMINI_API_KEY", "").strip("\"' ")
            new_model = vals.get("GEMINI_MODEL", "").strip("\"' ") or self.model_name
            if new_key and new_key != self.api_key:
                self.api_key = new_key
                self.model_name = new_model
                self._init_client()

    def _init_client(self):
        if not self.api_key or "YourActualKeyHere" in self.api_key:
            self._client = None
            logger.warning("GEMINI_API_KEY is not set or still has placeholder value.")
            return
        try:
            from google import genai
            self._client = genai.Client(api_key=self.api_key)
            logger.info(f"Initialized Google Gen AI Client with model {self.model_name}")
        except Exception as e:
            logger.error(f"Failed to initialize google-genai client: {e}")

    def is_configured(self) -> bool:
        self._refresh_key_if_changed()
        return bool(self._client and self.api_key and "YourActualKeyHere" not in self.api_key)

    def _generate_with_fallback(self, prompt: str):
        candidates = [self.model_name, "gemini-3.1-flash-lite", "gemini-3.5-flash-lite", "gemini-3.5-flash"]
        seen = set()
        deduped = [m for m in candidates if not (m in seen or seen.add(m))]
        last_err = None
        for m in deduped:
            try:
                return self._client.models.generate_content(model=m, contents=prompt)
            except Exception as e:
                logger.warning(f"Model {m} call failed: {e}")
                last_err = e
        raise last_err or RuntimeError("No model succeeded")

    async def generate_chat_response(
        self,
        query: str,
        context_chunks: List[Dict[str, Any]],
        history: List[Dict[str, str]] = []
    ) -> str:
        if not self.is_configured():
            return (
                "⚠️ **Gemini API Key Required**\n\n"
                "Please configure `GEMINI_API_KEY` in `backend/.env` to enable AI codebase question answering and reasoning.\n\n"
                f"**Retrieved Evidence Chunks ({len(context_chunks)} found):**\n" +
                "\n".join([f"- `{c['metadata'].get('file_path')}` (lines {c['metadata'].get('start_line')}-{c['metadata'].get('end_line')})" for c in context_chunks])
            )

        # Build context section
        context_str = ""
        for i, chunk in enumerate(context_chunks, 1):
            meta = chunk.get("metadata", {})
            f_path = meta.get("file_path", "unknown")
            s_line = meta.get("start_line", "?")
            e_line = meta.get("end_line", "?")
            content = chunk.get("content", "")
            context_str += f"\n--- CHUNK {i} [{f_path}:{s_line}-{e_line}] ---\n{content}\n"

        prompt = f"""{SYSTEM_RAG_PROMPT}

CODEBASE CONTEXT:
{context_str}

CONVERSATION HISTORY:
{json.dumps(history[-6:], indent=2) if history else "No previous history"}

USER QUESTION:
{query}

ANSWER:"""

        try:
            response = self._generate_with_fallback(prompt)
            return response.text or "No response generated by model."
        except Exception as e:
            logger.error(f"Gemini API generation error: {e}")
            return f"Error communicating with Gemini API: {str(e)}"

    async def stream_chat_response(
        self,
        query: str,
        context_chunks: List[Dict[str, Any]],
        history: List[Dict[str, str]] = []
    ) -> AsyncIterator[str]:
        if not self.is_configured():
            msg = (
                "⚠️ **Gemini API Key Required**\n\n"
                "Please configure `GEMINI_API_KEY` in `backend/.env` to enable AI chat.\n\n"
                f"Retrieved {len(context_chunks)} code context chunks from repository index."
            )
            for word in msg.split(" "):
                yield word + " "
            return

        context_str = ""
        for i, chunk in enumerate(context_chunks, 1):
            meta = chunk.get("metadata", {})
            f_path = meta.get("file_path", "unknown")
            s_line = meta.get("start_line", "?")
            e_line = meta.get("end_line", "?")
            content = chunk.get("content", "")
            context_str += f"\n--- CHUNK {i} [{f_path}:{s_line}-{e_line}] ---\n{content}\n"

        prompt = f"""{SYSTEM_RAG_PROMPT}

CODEBASE CONTEXT:
{context_str}

CONVERSATION HISTORY:
{json.dumps(history[-6:], indent=2) if history else "No previous history"}

USER QUESTION:
{query}

ANSWER:"""

        models_to_try = [self.model_name]
        if "3.1-flash-lite" not in self.model_name:
            models_to_try.append("gemini-3.1-flash-lite")

        streamed_any = False
        last_error = None
        for m in models_to_try:
            try:
                response = self._client.models.generate_content_stream(
                    model=m,
                    contents=prompt
                )
                for chunk in response:
                    if chunk.text:
                        streamed_any = True
                        yield chunk.text
                if streamed_any:
                    break
            except Exception as e:
                logger.warning(f"Streaming with model {m} failed: {e}")
                last_error = e

        if not streamed_any and last_error:
            logger.error(f"Error streaming from Gemini: {last_error}")
            yield f"\n\n[Error from Gemini API: {str(last_error)}]"

    async def analyze_architecture(self, file_summaries: List[Dict[str, Any]]) -> Dict[str, Any]:
        if not self.is_configured():
            return {
                "overview": "Configure GEMINI_API_KEY in backend/.env to generate deep AI architecture synthesis.",
                "modules": [],
                "entry_points": [],
                "relationships": [],
                "nodes": [],
                "edges": [],
                "mermaid_diagram": "graph TD\n  App[Application] --> Modules[Detected Source Modules]"
            }

        files_summary_str = json.dumps(file_summaries[:80], indent=2)
        prompt = f"""{ARCHITECTURE_ANALYSIS_PROMPT}

REPOSITORY STRUCTURE & FILES:
{files_summary_str}
"""
        try:
            response = self._generate_with_fallback(prompt)
            raw_text = response.text or "{}"
            # Extract JSON block
            json_match = re.search(r"```json\s*(\{.*?\})\s*```", raw_text, re.DOTALL)
            if json_match:
                return json.loads(json_match.group(1))
            return json.loads(raw_text)
        except Exception as e:
            logger.error(f"Error in architecture analysis: {e}")
            return {
                "overview": f"Architecture analysis encountered an error: {str(e)}",
                "modules": [],
                "entry_points": [],
                "relationships": [],
                "nodes": [],
                "edges": [],
                "mermaid_diagram": "graph TD\n  App[Application] --> Core[Codebase]"
            }

    async def analyze_bugs(self, code_samples: List[Dict[str, Any]]) -> Dict[str, Any]:
        if not self.is_configured():
            return {
                "summary": "Configure GEMINI_API_KEY to run AI bug and security scanning.",
                "findings": []
            }

        samples_str = json.dumps(code_samples[:20], indent=2)
        prompt = f"""{BUG_ANALYSIS_PROMPT}

CODE SAMPLES:
{samples_str}
"""
        try:
            response = self._generate_with_fallback(prompt)
            raw_text = response.text or "{}"
            json_match = re.search(r"```json\s*(\{.*?\})\s*```", raw_text, re.DOTALL)
            if json_match:
                return json.loads(json_match.group(1))
            return json.loads(raw_text)
        except Exception as e:
            logger.error(f"Error in bug analysis: {e}")
            return {
                "summary": f"Bug analysis could not be completed: {str(e)}",
                "findings": []
            }

    async def generate_tests(
        self,
        file_path: str,
        code_content: str,
        target_symbol: Optional[str] = None,
        framework: Optional[str] = None
    ) -> Dict[str, Any]:
        if not self.is_configured():
            return {
                "framework": framework or "pytest",
                "test_code": f"# Configure GEMINI_API_KEY in backend/.env to generate unit tests for {file_path}",
                "instructions": "Add your API key and retry.",
                "coverage_notes": ["No tests generated."]
            }

        prompt = f"""{TEST_GENERATION_PROMPT}

TARGET FILE: {file_path}
TARGET SYMBOL: {target_symbol or 'Whole file / Key functions'}
REQUESTED FRAMEWORK: {framework or 'Auto-detect best fit'}

SOURCE CODE:
{code_content[:8000]}
"""
        try:
            response = self._generate_with_fallback(prompt)
            raw_text = response.text or "{}"
            json_match = re.search(r"```json\s*(\{.*?\})\s*```", raw_text, re.DOTALL)
            if json_match:
                return json.loads(json_match.group(1))
            return json.loads(raw_text)
        except Exception as e:
            logger.error(f"Error generating tests: {e}")
            return {
                "framework": framework or "unittest",
                "test_code": f"# Error generating tests: {str(e)}",
                "instructions": "Check error log.",
                "coverage_notes": []
            }

gemini_client = GeminiClient()
